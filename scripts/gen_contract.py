#!/usr/bin/env python3
"""Generate the extension's TypeScript copy of the root-cause contract.

The contract JSON stays the single source of truth; the extension cannot read a
JSON file reliably from every install layout, so this table is generated and
checked by ``scripts/contract_check.py`` (a stale table fails CI).
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "storageops_cli" / "extensions" / "storageops" / "contract.generated.ts"

HEADER = """// Generated by scripts/gen_contract.py from contract/root-causes.json.
// Do not edit by hand; run `make contract` after changing the JSON.

export type DomainContract = {
  skill: string;
  ids: string[];
  aliases: Record<string, string>;
};

export const CONTRACT_VERSION = %s;

export const DOMAINS: Record<string, DomainContract> = %s;
"""


def normalize(term: str) -> str:
    return term.strip().lower().replace("_", "-")


def render(contract: dict) -> str:
    domains = {}
    for name in sorted(contract.get("domains", {})):
        spec = contract["domains"][name]
        ids = [entry["id"] for entry in spec.get("root_causes", [])]
        aliases = {}
        for entry in spec.get("root_causes", []):
            for alias in entry.get("aliases", []):
                aliases[normalize(alias)] = entry["id"]
        domains[name] = {"skill": spec.get("skill", ""), "ids": ids, "aliases": aliases}
    body = _ts(domains, 0)
    return HEADER % (_ts_string(contract.get("version", "")), body)


def _ts_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _ts(value, indent: int) -> str:
    pad = "  " * indent
    inner = "  " * (indent + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = ["{"]
        for key in value:
            lines.append(f"{inner}{_ts_string(key)}: {_ts(value[key], indent + 1)},")
        lines.append(f"{pad}}}")
        return "\n".join(lines)
    if isinstance(value, list):
        if not value:
            return "[]"
        items = [f"{inner}{_ts_string(item)}," for item in value]
        return "[\n" + "\n".join(items) + f"\n{pad}]"
    if isinstance(value, str):
        return _ts_string(value)
    raise TypeError(type(value))


def main() -> int:
    import json

    contract = json.loads((ROOT / "contract" / "root-causes.json").read_text(encoding="utf-8"))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(contract), encoding="utf-8")
    print(f"generated {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
